"""Lightweight photographic portrait rendering, driven by Windows speech visemes.
The source sheet is generated by imagegen. This module only renders the app's
frames; it does not use the camera or run a neural video model at runtime.
"""
import json,math,time,random
from pathlib import Path
import tkinter as tk

ASSETS=Path(__file__).resolve().parent/'assets'
VISEMES=[0,3,3,5,4,9,4,6,5,3,5,3,3,9,9,4,4,10,8,9,3,7]
COLORS={'idle':'#65e1bb','listening':'#65e1bb','thinking':'#b9a5ff','speaking':'#8dc6ff','approval':'#f0c87b','error':'#f0a2a2'}

def isolate_person(frame):
    import cv2,numpy as np
    count,labels,stats,_=cv2.connectedComponentsWithStats((frame[:,:,3]>100).astype(np.uint8))
    if count>1:
        largest=1+int(np.argmax(stats[1:,cv2.CC_STAT_AREA]))
        frame=frame.copy();frame[:,:,3][labels!=largest]=0
    return frame

class PortraitRenderer:
    def __init__(self):
        import cv2,numpy as np
        from PIL import Image
        self.metadata=json.loads((ASSETS/'kesara-photo-registration.json').read_text(encoding='utf-8'))
        self.frames=[]
        with Image.open(ASSETS/'kesara-photo-sheet.png') as sheet:
            columns,rows=self.metadata['grid']
            w,h=sheet.width//columns,sheet.height//rows
            for i in range(12):
                frame=np.array(sheet.crop(((i%columns)*w,(i//columns)*h,(i%columns+1)*w,(i//columns+1)*h)).convert('RGBA'))
                frame=isolate_person(frame)
                matrix=np.array(self.metadata['transforms'][i],dtype=np.float32)
                self.frames.append(cv2.warpAffine(frame,matrix,(w,h),flags=cv2.INTER_CUBIC,borderMode=cv2.BORDER_CONSTANT))
        self.body_frames=None;self.gesture_phase=0
        body_metadata=ASSETS/'kesara-photo-body-registration.json'
        if body_metadata.is_file():
            body=json.loads(body_metadata.read_text(encoding='utf-8'))
            self.source_flows=np.load(ASSETS/body['flow_file'])['flows']
            self.body_frames=[]
            with Image.open(ASSETS/'kesara-photo-body-sheet.png') as sheet:
                columns,rows=body['grid'];bw,bh=sheet.width//columns,sheet.height//rows
                for i in range(12):
                    frame=np.array(sheet.crop(((i%columns)*bw,(i//columns)*bh,(i%columns+1)*bw,(i//columns+1)*bh)).convert('RGBA'))
                    frame=isolate_person(frame)
                    matrix=np.array(body['transforms'][i],dtype=np.float32)
                    self.body_frames.append(cv2.warpAffine(frame,matrix,(bw,bh),flags=cv2.INTER_CUBIC,borderMode=cv2.BORDER_CONSTANT))
            matrix=np.array(body['photo_to_body'],dtype=np.float32)
            self.frames=[cv2.warpAffine(frame,matrix,(bw,bh),flags=cv2.INTER_CUBIC,borderMode=cv2.BORDER_CONSTANT) for frame in self.frames]
            for name in ('mouth','eyes'):
                x,y,rx,ry=self.metadata[name]
                center=matrix@np.array([x,y,1]);sx=np.linalg.norm(matrix[:,0]);sy=np.linalg.norm(matrix[:,1])
                self.metadata[name]=[float(center[0]),float(center[1]),float(rx*sx),float(ry*sy)]
            self.metadata['head']=body['head'];w,h=bw,bh
        self.shape=(w,h);self.cache=None;self.weights=np.zeros(12,dtype=np.float32);self.weights[0]=1
        self.last=time.monotonic();self.next_blink=self.last+random.uniform(2.5,5);self.blink_start=None
        self.rendered=0

    def resize(self,width,height):
        import cv2,numpy as np
        if self.cache and self.cache['size']==(width,height):return self.cache
        w,h=self.shape
        scale=min(width/w,height/h)
        size=(max(1,round(w*scale)),max(1,round(h*scale)))
        frames=[cv2.resize(frame,size,interpolation=cv2.INTER_AREA).astype(np.float32) for frame in self.frames]
        masks=[]
        for name in (('mouth','eyes','head') if self.body_frames else ('mouth','eyes')):
            x,y,rx,ry=self.metadata[name]
            mask=np.zeros((h,w),dtype=np.float32)
            cv2.ellipse(mask,(round(x),round(y)),(round(rx),round(ry)),0,0,360,1,-1)
            mask=cv2.GaussianBlur(mask,(0,0),max(1,w*.006))
            masks.append(cv2.resize(mask,size)[:,:,None])
        self.cache={'size':(width,height),'frames':frames,'mouth':masks[0],'eyes':masks[1],'image_size':size}
        if self.body_frames:
            from gesture_animation import resize_prepared
            body_frames=[cv2.resize(frame,size,interpolation=cv2.INTER_AREA).astype(np.float32) for frame in self.body_frames]
            self.cache.update(body_frames=body_frames,flows=resize_prepared(self.source_flows,size[0],size[1]),head=masks[2])
        return self.cache

    def render(self,width,height,mode='idle',viseme=0,now=None):
        import cv2,numpy as np
        from PIL import Image
        now=time.monotonic() if now is None else now
        dt=max(.001,min(.2,now-self.last));self.last=now
        cache=self.resize(width,height);frames=cache['frames']
        target=VISEMES[viseme] if mode=='speaking' and 0<=viseme<len(VISEMES) else (11 if mode=='idle' else 0)
        desired=np.zeros(12,dtype=np.float32);desired[target]=1
        self.weights+=(desired-self.weights)*(1-math.exp(-dt/.045))
        if self.body_frames:
            from gesture_animation import interpolate
            if mode=='speaking':self.gesture_phase=(self.gesture_phase+dt*11/5)%11
            elif self.gesture_phase<5.5:self.gesture_phase=max(0,self.gesture_phase-dt*11/.7)
            else:
                self.gesture_phase+=dt*11/.7
                if self.gesture_phase>=11:self.gesture_phase=0
            base=interpolate(cache['body_frames'],cache['flows'],self.gesture_phase)
            head_alpha=cache['head']*frames[0][:,:,3:4]/255
            base=base*(1-head_alpha)+frames[0]*head_alpha
        else:base=frames[0].copy()
        mouth=sum(frame*weight for frame,weight in zip(frames,self.weights) if weight>.001)
        base=base*(1-cache['mouth'])+mouth*cache['mouth']
        if now>=self.next_blink and self.blink_start is None:self.blink_start=now
        if self.blink_start is not None:
            p=(now-self.blink_start)/.22
            if p>=1:
                self.blink_start=None;self.next_blink=now+random.uniform(3,7)
            else:
                closure=math.sin(p*math.pi)
                eye=frames[0]*(1-min(1,closure*2))+frames[1]*max(0,1-abs(closure-.5)*2)+frames[2]*max(0,closure*2-1)
                base=base*(1-cache['eyes'])+eye*cache['eyes']
        # Small continuous posture changes; no swaps between entire head poses.
        iw,ih=cache['image_size'];angle=math.sin(now*.55)*.3
        if mode=='listening':angle+=.25
        matrix=cv2.getRotationMatrix2D((iw*.5,ih*.82),angle,1+math.sin(now*1.15)*.0015)
        matrix[1,2]+=math.sin(now*1.15)*.45
        base=cv2.warpAffine(np.clip(base,0,255).astype(np.uint8),matrix,(iw,ih),flags=cv2.INTER_LINEAR,borderMode=cv2.BORDER_CONSTANT)
        image=Image.fromarray(base)
        canvas=Image.new('RGBA',(width,height));canvas.alpha_composite(image,((width-iw)//2,height-ih))
        self.rendered+=1
        return canvas

class PhotoCharacter(tk.Canvas):
    COLORS=COLORS
    is_photo=True
    is_realistic=True
    rig=None
    rig_error=None
    def __init__(self,parent,width=180,height=156):
        from PIL import ImageTk
        super().__init__(parent,width=width,height=height,bg='#171f2c',highlightthickness=0)
        self.base_width=width;self.base_height=height;self.mode='idle';self.level=0;self.viseme=0;self.running=True
        self.renderer=PortraitRenderer();self.frames=self.renderer.frames
        self.image_item=self.create_image(0,0,anchor='nw')
        self.bind('<Destroy>',lambda event:setattr(self,'running',False))
        self.draw();self.after(33,self.animate)
        from voice import diagnostic
        diagnostic('avatar_ready',renderer='photographic_portrait')
    def set_state(self,mode):self.mode=mode if mode in COLORS else 'idle'
    def set_level(self,value):self.level=value
    def draw(self):
        from PIL import ImageTk
        width=self.winfo_width() if self.winfo_width()>5 else self.base_width
        height=self.winfo_height() if self.winfo_height()>5 else self.base_height
        frame=self.renderer.render(width,height,self.mode,self.viseme)
        if self.cget('bg')=='#ff00ff':
            import cv2,numpy as np
            alpha=np.array(frame.getchannel('A'))
            alpha=cv2.erode((alpha>=200).astype(np.uint8)*255,np.ones((3,3),np.uint8))
            from PIL import Image
            frame.putalpha(Image.fromarray(alpha))
        self.photo=ImageTk.PhotoImage(frame,master=self);self.itemconfigure(self.image_item,image=self.photo)
    def animate(self):
        if not self.running:return
        started=time.monotonic()
        if self.winfo_ismapped():self.draw()
        interval=1/24 if self.mode=='speaking' else (1/18 if self.mode=='listening' else 1/12)
        self.after(max(1,int((interval-(time.monotonic()-started))*1000)),self.animate)
