"""Read-only repository tools and approved, bounded test execution.

All filesystem operations resolve against a verified selected project root.
These are native tools, not free-form commands generated by an LLM.
"""
from pathlib import Path
import os
import re
import subprocess

IGNORED={'.git','.venv','venv','node_modules','__pycache__','.dart_tool',
         'build','dist','target','.idea','.gradle','.next','coverage','vendor',
         'third_party','third-party','speech-model','models','runtime','backups'}
PRIVATE={'.env','.env.local','.env.production','credentials.json','secrets.json',
         'approval-policy.json','model-settings.json','memory.json','voice-settings.json'}
MANIFESTS={'pom.xml':'Maven / Java','build.gradle':'Gradle / JVM',
           'build.gradle.kts':'Gradle / JVM','pubspec.yaml':'Flutter / Dart',
           'pyproject.toml':'Python','pytest.ini':'Python / pytest',
           'requirements.txt':'Python','package.json':'Node / JavaScript'}
SUFFIXES={'.py','.java','.kt','.dart','.ts','.tsx','.js','.jsx','.md',
          '.yaml','.yml','.toml','.xml','.gradle','.txt'}
MAX_VISITED=900
MAX_RESULTS=24

def _root(root):
    root=Path(root).resolve()
    if not root.is_dir():
        raise ValueError('Selected project directory does not exist: '+str(root))
    return root

def _files(root):
    visited=0
    for directory,dirs,filenames in os.walk(root,followlinks=False):
        current=Path(directory)
        depth=len(current.relative_to(root).parts)
        dirs[:]=[d for d in dirs if d not in IGNORED and depth<7 and
                 not (current/d).is_symlink()]
        for name in sorted(filenames):
            path=current/name
            if name in PRIVATE or name.startswith('.env') or path.is_symlink():
                continue
            if path.suffix.lower() not in SUFFIXES and name not in MANIFESTS:
                continue
            visited+=1
            if visited>MAX_VISITED:return
            try:
                if path.stat().st_size<=150000:
                    yield path
            except OSError:
                continue

def project_map(root):
    root=_root(root)
    paths=[p.relative_to(root).as_posix() for p in _files(root)]
    indicators=[label+' ('+name+')' for name,label in MANIFESTS.items() if (root/name).is_file()]
    entry=[p for p in paths if p in ('README.md','AGENTS.md','main.py','app.py',
                                    'kesara.py','desktop.py','launch.py',
                                    'src/main.py','lib/main.dart','package.json','pom.xml')]
    try:
        git=subprocess.run(['git','status','--short','--branch'],cwd=root,
                           capture_output=True,text=True,timeout=8,
                           errors='replace',check=False)
        gitstatus=git.stdout.strip()[:350] if git.returncode==0 else 'Not a Git worktree'
    except (OSError,subprocess.TimeoutExpired):
        gitstatus='Git status unavailable'
    return ('Project: '+str(root)+'\nTechnology manifests: '+(', '.join(indicators) or 'none detected')+
            '\nEntry points: '+(', '.join(entry) or 'not identified')+
            '\nSource candidates: '+str(len(paths))+' (bounded scan)'+
            '\nGit: '+gitstatus+
            '\nRepresentative files:\n'+'\n'.join(paths[:50]))

def search_code(root,query):
    root=_root(root)
    if not isinstance(query,str) or not query.strip() or len(query)>100:
        raise ValueError('Search term must be 1-100 characters')
    query=query.strip().casefold()
    matches=[]
    for path in _files(root):
        try:
            with path.open(encoding='utf-8',errors='replace') as stream:
                for line_number,line in enumerate(stream,1):
                    if query in line.casefold():
                        relative=path.relative_to(root).as_posix()
                        matches.append(f'{relative}:{line_number}: {line.strip()[:200]}')
                        if len(matches)>=MAX_RESULTS:
                            return '\n'.join(matches)+'\nResult limit reached.'
        except OSError:
            continue
    return '\n'.join(matches) if matches else 'No matching source lines in the bounded project scan.'

def suggested_test(root):
    root=_root(root)
    if (root/'pom.xml').is_file():return ('maven',['mvn','test'])
    if (root/'gradlew.bat').is_file() and os.name=='nt':return ('gradle',['cmd.exe','/c','gradlew.bat','test'])
    if (root/'gradlew').is_file() and os.name!='nt':return ('gradle',['./gradlew','test'])
    if (root/'build.gradle').is_file() or (root/'build.gradle.kts').is_file():
        return ('gradle',['gradle','test'])
    if (root/'pubspec.yaml').is_file():return ('flutter',['flutter','test'])
    if (root/'pyproject.toml').is_file() or (root/'pytest.ini').is_file() or (root/'tests').is_dir():
        return ('python',['python','-m','unittest','discover','-s','tests','-v'])
    return None

def test_project(root,confirm,timeout=180):
    root=_root(root)
    selected=suggested_test(root)
    if selected is None:
        return 'No supported test runner identified. No commands executed.'
    label,argv=selected
    command=' '.join(argv)
    if not confirm('TEST '+str(root)+'\n'+command):
        return 'User declined test execution. No commands executed.'
    try:
        result=subprocess.run(argv,cwd=root,capture_output=True,text=True,
                              timeout=timeout,errors='replace',check=False)
    except (OSError,subprocess.TimeoutExpired) as exc:
        return 'Tests could not complete ('+label+'): '+str(exc)
    output=(result.stdout+'\n'+result.stderr)[-11000:]
    return ('Test runner: '+label+'\nCommand: '+command+
            '\nExit code: '+str(result.returncode)+
            '\nResult: '+('PASS' if result.returncode==0 else 'FAIL')+
            '\nOutput:\n'+output)
